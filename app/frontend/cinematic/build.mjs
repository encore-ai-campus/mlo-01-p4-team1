import {build} from 'esbuild';
import {createHash} from 'node:crypto';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

// A separate, locked builder avoids changing the shared application dependency lock.
const root=dirname(fileURLToPath(import.meta.url));
const check=process.argv.includes('--check');
if(process.argv.slice(2).some(value=>value!=='--check'))throw new Error('Usage: node build.mjs [--check]');
const sha=buffer=>createHash('sha256').update(buffer).digest('hex');
const license=await readFile(resolve(root,'THREE-LICENSE.txt'),'utf8');
const result=await build({
  absWorkingDir:root,entryPoints:['scene.js'],bundle:true,write:false,minify:true,
  platform:'browser',format:'esm',target:'es2022',sourcemap:false,legalComments:'eof',
  banner:{js:'/*! Three.js 0.180.0\n'+license+'\n*/'},logLevel:'warning',
});
if(result.outputFiles.length!==1)throw new Error('Expected a self-contained scene bundle.');
const script=Buffer.from(new TextDecoder().decode(result.outputFiles[0].contents).replace(/[ \t]+(?=\r?\n)/g,''));
const stylesheet=await readFile(resolve(root,'style.css'));
const scriptHash=sha(script),styleHash=sha(stylesheet);
const scriptPath=`/assets/cinematic/seasons-${scriptHash.slice(0,16)}.js`;
const stylePath=`/assets/cinematic/seasons-${styleHash.slice(0,16)}.css`;
const generated='// Generated by frontend/cinematic/build.mjs; keep content hashes in immutable asset names.\n'+
  `export const SCENE_ASSET = ${JSON.stringify(scriptPath)};\n`+
  `export const STYLE_ASSET = ${JSON.stringify(stylePath)};\n`;
const outputs=[
  [resolve(root,'../public'+scriptPath),script],
  [resolve(root,'../public'+stylePath),stylesheet],
  [resolve(root,'../src/features/cinematic/generated.ts'),Buffer.from(generated)],
];
for(const [path,content] of outputs){
  if(check){
    const actual=await readFile(path).catch(()=>null);
    if(!actual||!actual.equals(Buffer.from(content)))throw new Error('Missing or stale generated asset: '+path.split('/').pop());
  }else{
    await mkdir(dirname(path),{recursive:true});
    await writeFile(path,content);
  }
}
console.log(JSON.stringify({status:'pass',mode:check?'check':'build',three:'0.180.0',script:scriptPath,scriptBytes:script.length,stylesheet:stylePath,stylesheetBytes:stylesheet.length}));
